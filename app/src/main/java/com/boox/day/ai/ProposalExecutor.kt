package com.boox.day.ai

import android.content.Context
import android.util.Log
import com.boox.day.data.ai.AgenticProposal
import com.boox.day.data.ai.ProposalAction
import com.boox.day.data.ai.ProposalExecutionResult
import com.boox.day.data.db.LocalEvent
import com.boox.day.data.db.LocalEventRepository
import com.boox.day.data.db.TaskRepository
import com.boox.day.editor.utils.SlotAllocator
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import kotlinx.coroutines.withContext
import java.time.LocalDate
import java.time.LocalTime
import java.time.ZoneId
import java.time.format.DateTimeFormatter

/**
 * Executes proposals generated by the Agentic Planning Service.
 *
 * Each proposal type has a specific execution path:
 * - MOVE_TASK: Updates task's dayDate and records migration
 * - CREATE_TIMEBLOCK: Creates a calendar event
 * - ADD_TASK: Adds a new task to the day's task list
 * - BREAK_DOWN_TASK: Opens the task breakdown dialog (returns action needed)
 * - FLAG_ZOMBIE: Informational (returns navigation hint)
 * - SCHEDULE_BUFFER: Creates a buffer event between meetings
 * - DELEGATE_OR_DROP: Informational (returns suggested action)
 * - BATCH_SIMILAR: Informational (returns grouping suggestion)
 *
 * @param context Android context
 * @param canvasHeight Canvas height for proper task positioning in MOVE_TASK
 * @param planningDate The date being planned (used for CREATE_TIMEBLOCK)
 * @param startPageIndex Page index to prefer for new task placement
 */
class ProposalExecutor(
    private val context: Context,
    private val canvasHeight: Float,
    private val planningDate: LocalDate,
    private val startPageIndex: Int = 0,
    private val taskRepository: TaskRepository = TaskRepository(context),
    private val localEventRepository: LocalEventRepository = LocalEventRepository(context),
    private val getInFlightProposalIds: () -> Set<String> = { emptySet() },
    private val getCompletedProposalIds: () -> Set<String> = { emptySet() },
    private val updateExecutionState: (inFlight: Set<String>, completed: Set<String>) -> Unit = { _, _ -> }
) {

    private val dateFormatter = DateTimeFormatter.ofPattern("yyyy-MM-dd")

    /** Serializes proposal execution state updates so rapid taps cannot race past the guard. */
    private val executionStateMutex = Mutex()

    companion object {
        private const val TAG = "ProposalExecutor"
    }

    /**
     * Execute a single proposal. Idempotent — calling twice with the same proposal is a no-op.
     *
     * @param proposal The proposal to execute
     * @param onNavigateToTask Callback when user should navigate to a specific task
     * @param onOpenBreakdownDialog Callback to open the task breakdown dialog
     * @return ProposalExecutionResult with success/failure and message
     */
    suspend fun execute(
        proposal: AgenticProposal,
        onNavigateToTask: ((taskId: String, date: String) -> Boolean)? = null,
        onOpenBreakdownDialog: ((taskId: String) -> Boolean)? = null
    ): ProposalExecutionResult {
        val preflightResult = executionStateMutex.withLock {
            val completed = getCompletedProposalIds()
            when {
                proposal.id in completed -> {
                    Log.d(TAG, "Proposal already completed: ${proposal.action} (${proposal.id})")
                    ProposalExecutionResult(
                        proposalId = proposal.id,
                        success = true,
                        message = "Already done"
                    )
                }
                proposal.id in getInFlightProposalIds() -> {
                    Log.d(TAG, "Proposal already in flight: ${proposal.action} (${proposal.id})")
                    ProposalExecutionResult(
                        proposalId = proposal.id,
                        success = false,
                        message = "Execution already in progress",
                        error = "Execution already in progress"
                    )
                }
                else -> {
                    updateExecutionState(getInFlightProposalIds() + proposal.id, completed)
                    null
                }
            }
        }
        if (preflightResult != null) return preflightResult

        Log.d(TAG, "Executing proposal: ${proposal.action} (${proposal.id})")

        val result = try {
            when (proposal.action) {
                ProposalAction.MOVE_TASK -> executeMoveTask(proposal)
                ProposalAction.CREATE_TIMEBLOCK -> executeCreateTimeblock(proposal)
                ProposalAction.ADD_TASK -> executeAddTask(proposal)
                ProposalAction.BREAK_DOWN_TASK -> executeBreakDownTask(proposal, onOpenBreakdownDialog)
                ProposalAction.FLAG_ZOMBIE -> executeFlagZombie(proposal, onNavigateToTask)
                ProposalAction.SCHEDULE_BUFFER -> executeScheduleBuffer(proposal)
                ProposalAction.DELEGATE_OR_DROP -> executeDelegateOrDrop(proposal)
                ProposalAction.BATCH_SIMILAR -> executeBatchSimilar(proposal)
            }
        } catch (e: Exception) {
            Log.e(TAG, "Failed to execute proposal ${proposal.id}", e)
            ProposalExecutionResult(
                proposalId = proposal.id,
                success = false,
                message = "Execution failed",
                error = e.message
            )
        }
        executionStateMutex.withLock {
            val updatedInFlight = getInFlightProposalIds() - proposal.id
            val updatedCompleted = if (result.success) {
                getCompletedProposalIds() + proposal.id
            } else {
                getCompletedProposalIds()
            }
            updateExecutionState(updatedInFlight, updatedCompleted)
        }

        return result
    }

    /**
     * Move a task to a different date.
     * Also records the migration for zombie tracking.
     */
    private suspend fun executeMoveTask(proposal: AgenticProposal): ProposalExecutionResult {
        val taskId = proposal.taskId
            ?: return failResult(proposal.id, "No task specified")

        val targetDate = proposal.targetDate
            ?: return failResult(proposal.id, "No target date specified")

        // Validate target date
        val targetLocalDate = try {
            LocalDate.parse(targetDate, dateFormatter)
        } catch (e: Exception) {
            return failResult(proposal.id, "Invalid target date: $targetDate")
        }

        // Get the task
        val task = withContext(Dispatchers.IO) {
            taskRepository.getById(taskId)
        }
            ?: return failResult(proposal.id, "Task not found")

        // Record the original date for migration tracking
        val originalDate = task.originalDate ?: task.dayDate

        // Find an available slot on the target date
        val targetDateStr = targetLocalDate.format(dateFormatter)

        // Move to first available page on target date using the existing moveTaskWithStrokes method
        val moveResult = withContext(Dispatchers.IO) {
            val result = taskRepository.moveTaskWithStrokes(
                task = task,
                targetDate = targetDateStr,
                targetPageIndex = 0,
                canvasHeight = canvasHeight, // Use actual canvas height for proper row positioning
                context = context
            )
            if (result.success) {
                // T11 (Oct 2026): count the deferral on the row that now holds the task
                taskRepository.recordTaskMigration(result.movedTaskId ?: taskId, originalDate)
            }
            result
        }

        if (!moveResult.success) {
            return failResult(proposal.id, moveResult.errorReason?.name ?: "Failed to move task")
        }

        Log.d(TAG, "Moved task $taskId to $targetDate")

        return ProposalExecutionResult(
            proposalId = proposal.id,
            success = true,
            message = "Task moved to $targetDate",
            resultPageIndex = moveResult.targetPageIndex,
            affectedDate = targetDateStr
        )
    }

    /**
     * Create a calendar event for focused work time.
     */
    private suspend fun executeCreateTimeblock(proposal: AgenticProposal): ProposalExecutionResult {
        val timeBlock = proposal.suggestedTimeBlock
            ?: return failResult(proposal.id, "No time block specified")

        // Use proposal.targetDate if set, otherwise use planningDate
        val eventDate = proposal.targetDate?.let {
            runCatching { LocalDate.parse(it, dateFormatter) }.getOrNull()
        } ?: planningDate

        // Parse times
        val startTime = try {
            LocalTime.parse(timeBlock.startTime)
        } catch (e: Exception) {
            return failResult(proposal.id, "Invalid start time: ${timeBlock.startTime}")
        }

        val endTime = try {
            LocalTime.parse(timeBlock.endTime)
        } catch (e: Exception) {
            return failResult(proposal.id, "Invalid end time: ${timeBlock.endTime}")
        }

        // Convert to epoch millis using the correct event date
        val startInstant = eventDate.atTime(startTime).atZone(ZoneId.systemDefault()).toInstant()
        val endInstant = eventDate.atTime(endTime).atZone(ZoneId.systemDefault()).toInstant()

        // Create the event
        val dayIdStr = eventDate.format(dateFormatter)
        val event = LocalEvent(
            title = timeBlock.title,
            dayId = dayIdStr,
            endDayId = dayIdStr,
            startTime = startInstant.toEpochMilli(),
            endTime = endInstant.toEpochMilli(),
            isAllDay = false,
            description = if (timeBlock.isDeepWork) "Deep work block created by AI planner" else "Focus time block"
        )

        val createdEvent = withContext(Dispatchers.IO) {
            localEventRepository.createEvent(event)
        }

        Log.d(TAG, "Created time block: ${timeBlock.title} ${timeBlock.startTime}-${timeBlock.endTime}")

        return ProposalExecutionResult(
            proposalId = proposal.id,
            success = true,
            message = "Created \"${timeBlock.title}\" from ${timeBlock.startTime} to ${timeBlock.endTime}",
            affectedDate = dayIdStr,
            createdEventId = createdEvent.id
        )
    }

    /**
     * Add a new task to the day's task list.
     */
    private suspend fun executeAddTask(proposal: AgenticProposal): ProposalExecutionResult {
        val taskText = proposal.taskText?.trim().orEmpty()
        if (taskText.isBlank()) {
            return failResult(proposal.id, "No task text specified")
        }

        val dateStr = planningDate.format(dateFormatter)
        val slot = SlotAllocator.allocateSingle(
            date = dateStr,
            canvasHeight = canvasHeight,
            taskRepository = taskRepository,
            startPageIndex = startPageIndex
        ) ?: return failResult(proposal.id, "No empty slots available")

        val isValid = SlotAllocator.validateBeforeWrite(slot.task, canvasHeight, taskRepository)
        if (!isValid) {
            return failResult(proposal.id, "Slot no longer available")
        }

        withContext(Dispatchers.IO) {
            taskRepository.setTypedText(slot.task.id, taskText)
        }

        return ProposalExecutionResult(
            proposalId = proposal.id,
            success = true,
            message = "Task added",
            resultPageIndex = slot.pageIndex,
            affectedDate = dateStr,
            createdTaskId = slot.task.id
        )
    }

    /**
     * Trigger the task breakdown dialog.
     * Returns a hint to open the dialog - actual breakdown is user-driven.
     */
    private fun executeBreakDownTask(
        proposal: AgenticProposal,
        onOpenBreakdownDialog: ((taskId: String) -> Boolean)?
    ): ProposalExecutionResult {
        val taskId = proposal.taskId
            ?: return failResult(proposal.id, "No task specified")

        // Trigger the breakdown dialog
        val openedDialog = onOpenBreakdownDialog?.invoke(taskId) == true
        if (!openedDialog) {
            return failResult(proposal.id, "Could not open task breakdown")
        }

        return ProposalExecutionResult(
            proposalId = proposal.id,
            success = true,
            message = "Opening task breakdown dialog..."
        )
    }

    /**
     * Flag a zombie task for user attention.
     * This is informational - navigates to the task for user decision.
     */
    private suspend fun executeFlagZombie(
        proposal: AgenticProposal,
        onNavigateToTask: ((taskId: String, date: String) -> Boolean)?
    ): ProposalExecutionResult {
        val taskId = proposal.taskId
            ?: return failResult(proposal.id, "No task specified")

        val task = withContext(Dispatchers.IO) {
            taskRepository.getById(taskId)
        }
            ?: return failResult(proposal.id, "Task not found")

        // Navigate to the task
        val navigated = onNavigateToTask?.invoke(taskId, task.dayDate) == true
        if (!navigated) {
            return failResult(proposal.id, "Could not navigate to task")
        }

        val zombieInfo = proposal.zombieInfo
        val suggestion = zombieInfo?.suggestion?.displayName ?: "Review and decide"

        return ProposalExecutionResult(
            proposalId = proposal.id,
            success = true,
            message = "Navigating to zombie task. Suggestion: $suggestion"
        )
    }

    /**
     * Create a buffer event between meetings.
     */
    private suspend fun executeScheduleBuffer(proposal: AgenticProposal): ProposalExecutionResult {
        val timeBlock = proposal.suggestedTimeBlock
            ?: return failResult(proposal.id, "No buffer time specified")

        // Reuse time block creation logic
        return executeCreateTimeblock(proposal.copy(
            suggestedTimeBlock = timeBlock.copy(
                title = "Buffer: ${timeBlock.title}",
                isDeepWork = false
            )
        ))
    }

    /**
     * Delegate or drop suggestion - informational.
     */
    private fun executeDelegateOrDrop(proposal: AgenticProposal): ProposalExecutionResult {
        val taskId = proposal.taskId
            ?: return failResult(proposal.id, "No task specified")

        // This is informational - user decides
        return ProposalExecutionResult(
            proposalId = proposal.id,
            success = true,
            message = "Consider: ${proposal.reason}"
        )
    }

    /**
     * Batch similar tasks suggestion - informational.
     */
    private fun executeBatchSimilar(proposal: AgenticProposal): ProposalExecutionResult {
        // Informational - suggest batching
        return ProposalExecutionResult(
            proposalId = proposal.id,
            success = true,
            message = proposal.description
        )
    }

    /**
     * Helper to create failure results.
     */
    private fun failResult(proposalId: String, error: String): ProposalExecutionResult {
        Log.w(TAG, "Proposal $proposalId failed: $error")
        return ProposalExecutionResult(
            proposalId = proposalId,
            success = false,
            message = "Failed",
            error = error
        )
    }
}
