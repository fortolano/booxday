/**
 * Requests a full-screen GC refresh to clear ghosting without changing content.
 *
 * This uses `EpdController.applyGCOnce()`, which is the documented way to trigger
 * a one-time full refresh on Boox devices. `repaintEveryThing()` with an
 * UpdateMode argument proved unreliable on some firmware versions.
 *
 * This call is intentionally global (no view parameter) and should be used
 * sparingly from explicit user actions (e.g., a "Screen Refresh" menu item).
 */
fun refreshScreen() {
    try {
        EpdController.applyGCOnce()
        einkLogger.d("Requested full screen GC refresh via applyGCOnce()")
    } catch (e: Exception) {
        einkLogger.e("Failed to request screen refresh: ${e.message}", e)
    }
}

/**
 * Refresh only the canvas region with high-quality GC mode.
 * Called from eraser menu "Refresh Canvas" option to clear ghosting
 * without flashing the toolbar or calendar areas.
 *
 * Uses UpdateMode.GC for best quality ghosting removal.
 *
 * @param view The DrawCanvas view to refresh
 */
fun refreshCanvasRegion(view: View) {
    try {
        val width = view.width
        val height = view.height

        if (width <= 0 || height <= 0) {
            einkLogger.w("refreshCanvasRegion: Invalid view dimensions ($width x $height)")
            return
        }

        // Use GC mode for best quality (full ghosting removal)
        // No offset - refresh the entire canvas view bounds
        EpdController.refreshScreenRegion(
            view,
            0,      // left (relative to view)
            0,      // top (relative to view)
            width,
            height,
            UpdateMode.GC  // GC = best quality, complete ghosting removal
        )
        einkLogger.d("Canvas refresh (GC mode): ${width}x${height}")
    } catch (e: Exception) {
        einkLogger.e("Failed to refresh canvas region: ${e.message}", e)
    }
}



