/**
 * Inline action legend — compact horizontal strip showing only action types present in results.
 * Always visible, no tap required.
 */
@Composable
private fun InlineActionLegend(actions: List<ProposalAction>) {
    if (actions.isEmpty()) return

    Row(
        modifier = Modifier
            .fillMaxWidth()
            .background(EInkTheme.Colors.selectedGray, RoundedCornerShape(6.dp))
            .padding(horizontal = 10.dp, vertical = 6.dp),
        horizontalArrangement = Arrangement.spacedBy(12.dp),
        verticalAlignment = Alignment.CenterVertically
    ) {
        actions.forEach { action ->
            Row(
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.spacedBy(4.dp)
            ) {
                Icon(
                    imageVector = getActionIcon(action),
                    contentDescription = null,
                    tint = EInkTheme.Colors.darkGray,
                    modifier = Modifier.size(15.dp)
                )
                Text(
                    text = getActionDescription(action),
                    fontSize = EInkTheme.Typography.labelSmall,
                    color = EInkTheme.Colors.darkGray,
                    maxLines = 1
                )
            }
        }
    }
}

/**
 * Format duration in minutes to a readable string.
 * Examples: "30m", "1h", "1h 30m", "2h"
 */
private fun formatDuration(minutes: Int): String {
    return when {
        minutes < 60 -> "${minutes}m"
        minutes % 60 == 0 -> "${minutes / 60}h"
        else -> "${minutes / 60}h ${minutes % 60}m"
    }
}

/**
 * Build time info string for proposal cards.
 * Shows estimated duration and suggested time slot if available.
 */
private fun buildTimeInfoString(proposal: AgenticProposal): String? {
    val parts = mutableListOf<String>()

    // Add suggested time slot
    proposal.suggestedTimeBlock?.let { block ->
        parts.add("Suggested: ${block.startTime}")
    }

    // Add estimated duration
    proposal.estimatedMinutes?.let { mins ->
        parts.add("Est. time: ${formatDuration(mins)}")
    }

    return if (parts.isNotEmpty()) parts.joinToString(" · ") else null
}
