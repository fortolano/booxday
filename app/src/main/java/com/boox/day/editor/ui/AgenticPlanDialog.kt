/**
 * Agentic Plan Dialog - AI-powered day planning with actionable proposals.
 *
 * Displays the "Plan My Day" proposals generated by the Agentic Planning Service.
 * Each proposal can be executed or skipped with a single tap.
 *
 * E-ink optimized: Popup (not Dialog), noRippleClickable, EInkTheme constants.
 */
@Composable
fun AgenticPlanDialog(
    planResult: AgenticPlanResult?,
    processingState: AgenticPlanProcessingState,
    completedProposalIds: Set<String> = emptySet(),
    inFlightProposalIds: Set<String> = emptySet(),
    onExecuteProposal: (AgenticProposal) -> Unit,
    onSkipProposal: (AgenticProposal) -> Unit,
    onDismiss: () -> Unit,
    onRetry: () -> Unit = {}
) {
    Popup(
        alignment = Alignment.Center,
        onDismissRequest = {
            if (processingState !is AgenticPlanProcessingState.Processing &&
                processingState !is AgenticPlanProcessingState.Executing) {
                onDismiss()
            }
        },
        properties = PopupProperties(
            focusable = true,
            dismissOnBackPress = processingState is AgenticPlanProcessingState.Ready ||
                                 processingState is AgenticPlanProcessingState.Error,
            dismissOnClickOutside = processingState is AgenticPlanProcessingState.Ready ||
                                    processingState is AgenticPlanProcessingState.Error
        )
    ) {
        Box(
            modifier = Modifier
                .width(EInkTheme.PopupOverlay.wideWidth)
                .heightIn(max = EInkTheme.PopupOverlay.maxHeight)  // Oct 2026: was 740 dp, taller than the Go 6 allows
                .background(EInkTheme.PopupOverlay.background, RoundedCornerShape(EInkTheme.Global.cornerRadius))
                .border(EInkTheme.PopupOverlay.borderWidth, EInkTheme.PopupOverlay.borderColor, RoundedCornerShape(EInkTheme.Global.cornerRadius))
        ) {
            Column(
                modifier = Modifier.padding(EInkTheme.PopupOverlay.padding)
            ) {
                // Header
                DialogHeader(
                    processingState = processingState,
                    planResult = planResult,
                    onDismiss = onDismiss
                )

                Spacer(Modifier.height(12.dp))

                // Content based on state
                when (processingState) {
                    is AgenticPlanProcessingState.Processing -> {
                        ProcessingContent(stageMessage = processingState.stageMessage)
                    }

                    is AgenticPlanProcessingState.Executing -> {
                        ProcessingContent(stageMessage = "Executing proposal...")
                    }

                    is AgenticPlanProcessingState.Error -> {
                        ErrorContent(
                            message = processingState.message,
                            onRetry = onRetry,
                            onDismiss = onDismiss
                        )
                    }

                    is AgenticPlanProcessingState.Ready -> {
                        if (planResult == null || !planResult.hasProposals) {
                            NoProposalsContent(
                                summary = planResult?.summary,
                                onDismiss = onDismiss
                            )
                        } else {
                            ProposalsContent(
                                modifier = Modifier.weight(1f, fill = false),
                                planResult = planResult,
                                completedProposalIds = completedProposalIds,
                                inFlightProposalIds = inFlightProposalIds,
                                onExecuteProposal = onExecuteProposal,
                                onSkipProposal = onSkipProposal,
                                onDone = onDismiss
                            )
                        }
                    }
                }
            }
        }
    }
}

@Composable
private fun DialogHeader(
    processingState: AgenticPlanProcessingState,
    planResult: AgenticPlanResult?,
    onDismiss: () -> Unit
) {
    // Wrap in Box so popup doesn't affect Row layout
    Box(modifier = Modifier.fillMaxWidth()) {
        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.SpaceBetween,
            verticalAlignment = Alignment.Top
        ) {
            Column(modifier = Modifier.weight(1f)) {
                Text(
                    text = "Optimize My Day",
                    fontSize = EInkTheme.PopupOverlay.titleFontSize,
                    fontWeight = FontWeight.Bold,
                    color = EInkTheme.PopupOverlay.titleColor
                )
                // Oct 2026: Vacation changes the plan, so say so while it's on
                com.boox.day.ui.components.VacationNotice(modifier = Modifier.padding(vertical = 4.dp))

                if (planResult != null && processingState is AgenticPlanProcessingState.Ready) {
                    // Capacity status
                    Text(
                        text = planResult.capacityStatus,
                        fontSize = EInkTheme.Typography.labelSmall,
                        color = EInkTheme.Colors.gray
                    )

                    // Commitment summary (e.g., "5 tasks (est. 2h 30m of 4h free)")
                    planResult.getCommitmentSummary()?.let { summary ->
                        Text(
                            text = summary,
                            fontSize = EInkTheme.Typography.labelSmall,
                            fontWeight = FontWeight.Medium,
                            color = EInkTheme.Colors.darkGray
                        )
                    }

                    // Free time slots
                    if (planResult.freeSlots.isNotEmpty()) {
                        Row(
                            modifier = Modifier.padding(top = 4.dp),
                            horizontalArrangement = Arrangement.spacedBy(6.dp),
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            Text(
                                text = "Free:",
                                fontSize = EInkTheme.Typography.labelSmall,
                                color = EInkTheme.Colors.gray
                            )
                            planResult.freeSlots.take(3).forEach { slot ->
                                Text(
                                    text = "${slot.startTime}-${slot.endTime}",
                                    fontSize = 12.sp,
                                    color = EInkTheme.Colors.darkGray,
                                    modifier = Modifier
                                        .background(
                                            EInkTheme.Colors.selectedGray,
                                            RoundedCornerShape(4.dp)
                                        )
                                        .padding(horizontal = 6.dp, vertical = 2.dp)
                                )
                            }
                            if (planResult.freeSlots.size > 3) {
                                Text(
                                    text = "+${planResult.freeSlots.size - 3}",
                                    fontSize = 12.sp,
                                    color = EInkTheme.Colors.gray
                                )
                            }
                        }
                    }
                }
            }

            // Header buttons (help + close)
            if (processingState !is AgenticPlanProcessingState.Processing &&
                processingState !is AgenticPlanProcessingState.Executing) {
                // Close button
                Box(
                    modifier = Modifier
                        .size(EInkTheme.Global.touchTarget)
                        .border(EInkTheme.Global.borderWidth, EInkTheme.Colors.gray, RoundedCornerShape(EInkTheme.Global.cornerRadius))
                        .noRippleClickable { onDismiss() },
                    contentAlignment = Alignment.Center
                ) {
                    Icon(
                        imageVector = Icons.Default.Close,
                        contentDescription = "Close",
                        tint = EInkTheme.Colors.primary,
                        modifier = Modifier.size(EInkTheme.Global.iconSize)
                    )
                }
            }
        }
    }
}

