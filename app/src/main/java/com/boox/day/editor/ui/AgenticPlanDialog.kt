@Composable
private fun TimelineProposalItem(
    proposal: AgenticProposal,
    isActioned: Boolean,
    onExecute: () -> Unit,
    onSkip: () -> Unit
) {
    val priorityLevel = proposal.getPriorityLevel()

    Row(
        modifier = Modifier.fillMaxWidth(),
        verticalAlignment = Alignment.Top
    ) {
        // Time column (left)
        Column(
            modifier = Modifier.width(65.dp),
            horizontalAlignment = Alignment.End
        ) {
            proposal.suggestedTimeBlock?.let { block ->
                Text(
                    text = block.startTime,
                    fontSize = EInkTheme.Typography.bodySmall,
                    fontWeight = FontWeight.Bold,
                    color = if (isActioned) EInkTheme.Colors.gray else EInkTheme.Colors.primary
                )
                proposal.estimatedMinutes?.let { mins ->
                    Text(
                        text = formatDuration(mins),
                        fontSize = 12.sp,
                        color = EInkTheme.Colors.gray
                    )
                }
            } ?: run {
                // No specific time - show estimate if available
                proposal.estimatedMinutes?.let { mins ->
                    Text(
                        text = formatDuration(mins),
                        fontSize = EInkTheme.Typography.bodySmall,
                        fontWeight = FontWeight.Medium,
                        color = EInkTheme.Colors.gray
                    )
                } ?: Text(
                    text = "—",
                    fontSize = EInkTheme.Typography.bodySmall,
                    color = EInkTheme.Colors.gray
                )
            }
        }

        // Vertical line connector
        Box(
            modifier = Modifier
                .padding(horizontal = 8.dp)
                .width(2.dp)
                .height(60.dp)
                .background(
                    if (isActioned) EInkTheme.Colors.selectedGray else EInkTheme.Colors.gray
                )
        )

        // Compact proposal card (right)
        Column(
            modifier = Modifier
                .weight(1f)
                .background(
                    if (isActioned) EInkTheme.Colors.selectedGray else EInkTheme.Colors.offWhite,
                    RoundedCornerShape(4.dp)
                )
                .border(
                    if (priorityLevel == ProposalPriority.HIGH && !isActioned) 2.dp else EInkTheme.Global.borderWidth,
                    if (isActioned) EInkTheme.Colors.gray
                    else if (priorityLevel == ProposalPriority.HIGH) EInkTheme.Colors.primary
                    else EInkTheme.Colors.darkGray,
                    RoundedCornerShape(4.dp)
                )
                .padding(8.dp)
        ) {
            // Header row
            Row(
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.spacedBy(4.dp)
            ) {
                Icon(
                    imageVector = getActionIcon(proposal.action),
                    contentDescription = proposal.action.displayName,
                    tint = if (isActioned) EInkTheme.Colors.gray else EInkTheme.Colors.primary,
                    modifier = Modifier.size(14.dp)
                )
                Text(
                    text = proposal.title,
                    fontSize = EInkTheme.Typography.bodySmall,
                    fontWeight = if (priorityLevel == ProposalPriority.HIGH) FontWeight.Bold else FontWeight.Medium,
                    color = if (isActioned) EInkTheme.Colors.gray else EInkTheme.Colors.primary,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis,
                    modifier = Modifier.weight(1f)
                )
                if (isActioned) {
                    Icon(
                        imageVector = Icons.Default.Check,
                        contentDescription = "Done",
                        tint = EInkTheme.Colors.gray,
                        modifier = Modifier.size(16.dp)
                    )
                }
            }

            // Task text (only if different from title)
            if (!proposal.taskText.isNullOrBlank() && proposal.taskText != proposal.title) {
                Text(
                    text = proposal.taskText,
                    fontSize = 13.sp,
                    color = EInkTheme.Colors.darkGray,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis,
                    modifier = Modifier.padding(top = 2.dp)
                )
            }

            // Action buttons (if not actioned)
            if (!isActioned) {
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(top = 4.dp),
                    horizontalArrangement = Arrangement.End
                ) {
                    Text(
                        text = "Skip",
                        fontSize = 12.sp,
                        color = EInkTheme.Colors.gray,
                        modifier = Modifier
                            .noRippleClickable { onSkip() }
                            .padding(horizontal = 8.dp, vertical = 2.dp)
                    )
                    Text(
                        text = getExecuteButtonText(proposal.action),
                        fontSize = 12.sp,
                        fontWeight = FontWeight.Medium,
                        color = EInkTheme.Colors.primary,
                        modifier = Modifier
                            .noRippleClickable { onExecute() }
                            .padding(horizontal = 8.dp, vertical = 2.dp)
                    )
                }
            }
        }
    }
}

@Composable
private fun ProposalCard(
    proposal: AgenticProposal,
    isActioned: Boolean,
    onExecute: () -> Unit,
    onSkip: () -> Unit
) {
    val action = proposal.action
    val priorityLevel = proposal.getPriorityLevel()

    // Priority-based visual styling
    val cardBorderWidth = when (priorityLevel) {
        ProposalPriority.HIGH -> 2.dp
        else -> EInkTheme.Global.borderWidth
    }
    val cardBorderColor = when {
        isActioned -> EInkTheme.Colors.gray
        priorityLevel == ProposalPriority.HIGH -> EInkTheme.Colors.primary
        priorityLevel == ProposalPriority.LOW -> EInkTheme.Colors.gray
        else -> EInkTheme.Colors.darkGray
    }
    val badgeAlpha = when {
        isActioned -> 0.2f
        priorityLevel == ProposalPriority.HIGH -> 0.15f
        priorityLevel == ProposalPriority.LOW -> 0.08f
        else -> 0.1f
    }
    val titleFontWeight = when (priorityLevel) {
        ProposalPriority.HIGH -> FontWeight.Bold
        else -> FontWeight.Medium
    }

    Box(
        modifier = Modifier
            .fillMaxWidth()
            .background(
                if (isActioned) EInkTheme.Colors.selectedGray else EInkTheme.Colors.offWhite,
                RoundedCornerShape(EInkTheme.Global.cornerRadius)
            )
            .border(
                cardBorderWidth,
                cardBorderColor,
                RoundedCornerShape(EInkTheme.Global.cornerRadius)
            )
            .padding(12.dp)
    ) {
        Column(
            modifier = Modifier.fillMaxWidth(),
            verticalArrangement = Arrangement.spacedBy(8.dp)
        ) {
            // Header row: Action badge + Title + Priority indicator
            Row(
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.spacedBy(8.dp)
            ) {
                // Action type badge with priority-based alpha
                Box(
                    modifier = Modifier
                        .background(
                            if (isActioned) EInkTheme.Colors.gray.copy(alpha = badgeAlpha)
                            else EInkTheme.Colors.primary.copy(alpha = badgeAlpha),
                            RoundedCornerShape(4.dp)
                        )
                        .padding(horizontal = 6.dp, vertical = 4.dp),
                    contentAlignment = Alignment.Center
                ) {
                    Icon(
                        imageVector = getActionIcon(action),
                        contentDescription = action.displayName,
                        tint = if (isActioned) EInkTheme.Colors.gray else EInkTheme.Colors.primary,
                        modifier = Modifier.size(16.dp)
                    )
                }

                // Title with priority-based font weight
                Text(
                    text = proposal.title,
                    fontSize = EInkTheme.Typography.bodyMedium,
                    fontWeight = titleFontWeight,
                    color = if (isActioned) EInkTheme.Colors.gray else EInkTheme.Colors.primary,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis,
                    modifier = Modifier.weight(1f)
                )

                // High priority indicator
                if (priorityLevel == ProposalPriority.HIGH && !isActioned) {
                    Text(
                        text = "High Impact",
                        fontSize = 12.sp,
                        fontWeight = FontWeight.Medium,
                        color = EInkTheme.Colors.primary,
                        modifier = Modifier
                            .background(
                                EInkTheme.Colors.primary.copy(alpha = 0.1f),
                                RoundedCornerShape(4.dp)
                            )
                            .padding(horizontal = 6.dp, vertical = 2.dp)
                    )
                }

                // Actioned indicator
                if (isActioned) {
                    Icon(
                        imageVector = Icons.Default.Check,
                        contentDescription = "Done",
                        tint = EInkTheme.Colors.gray,
                        modifier = Modifier.size(20.dp)
                    )
                }
            }

            // Task text (only if different from title — avoid duplicate display)
            if (!proposal.taskText.isNullOrBlank() && proposal.taskText != proposal.title) {
                Text(
                    text = "\"${proposal.taskText}\"",
                    fontSize = EInkTheme.Typography.bodySmall,
                    color = EInkTheme.Colors.darkGray,
                    maxLines = 2,
                    overflow = TextOverflow.Ellipsis
                )
            }

            // Description
            Text(
                text = proposal.description,
                fontSize = EInkTheme.Typography.labelSmall,
                color = EInkTheme.Colors.gray,
                maxLines = 2,
                overflow = TextOverflow.Ellipsis
            )

            // Time estimate and suggested slot
            val timeInfo = buildTimeInfoString(proposal)
            if (timeInfo != null) {
                Text(
                    text = timeInfo,
                    fontSize = 12.sp,
                    color = if (isActioned) EInkTheme.Colors.gray else EInkTheme.Colors.darkGray,
                    modifier = Modifier.padding(top = 4.dp)
                )
            }

            // Action buttons (only if not actioned)
            if (!isActioned) {
                Spacer(Modifier.height(4.dp))

                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    // Skip button
                    Box(
                        modifier = Modifier
                            .weight(1f)
                            .height(36.dp)
                            .background(EInkTheme.Colors.offWhite, RoundedCornerShape(EInkTheme.Global.cornerRadius))
                            .border(EInkTheme.Global.borderWidth, EInkTheme.Colors.gray, RoundedCornerShape(EInkTheme.Global.cornerRadius))
                            .noRippleClickable { onSkip() },
                        contentAlignment = Alignment.Center
                    ) {
                        Text(
                            text = "Skip",
                            fontSize = EInkTheme.Typography.labelMedium,
                            color = EInkTheme.Colors.gray
                        )
                    }

                    // Execute button
                    Box(
                        modifier = Modifier
                            .weight(1f)
                            .height(36.dp)
                            .background(EInkTheme.Colors.primary, RoundedCornerShape(EInkTheme.Global.cornerRadius))
                            .noRippleClickable { onExecute() },
                        contentAlignment = Alignment.Center
                    ) {
                        Text(
                            text = getExecuteButtonText(action),
                            fontSize = EInkTheme.Typography.labelMedium,
                            fontWeight = FontWeight.Medium,
                            color = EInkTheme.Colors.white
                        )
                    }
                }
            }
        }
    }
}

