@Composable
private fun ProposalsContent(
    modifier: Modifier = Modifier,
    planResult: AgenticPlanResult,
    completedProposalIds: Set<String>,
    inFlightProposalIds: Set<String>,
    onExecuteProposal: (AgenticProposal) -> Unit,
    onSkipProposal: (AgenticProposal) -> Unit,
    onDone: () -> Unit
) {
    // View mode toggle state
    var viewMode by remember { mutableStateOf(OptimizeViewMode.LIST) }

    val handledProposalIds = remember(completedProposalIds, inFlightProposalIds) {
        completedProposalIds + inFlightProposalIds
    }
    val remainingProposals = planResult.proposals.filter { it.id !in handledProposalIds }

    // Scroll state for list view
    val scrollState = rememberLazyListState()
    val showScrollIndicator by remember {
        derivedStateOf {
            val lastVisibleItem = scrollState.layoutInfo.visibleItemsInfo.lastOrNull()
            val totalItems = scrollState.layoutInfo.totalItemsCount
            lastVisibleItem != null && lastVisibleItem.index < totalItems - 1
        }
    }

    Column(modifier = modifier.fillMaxWidth()) {
        // Summary
        if (!planResult.summary.isNullOrBlank()) {
            Text(
                text = planResult.summary,
                fontSize = EInkTheme.Typography.bodySmall,
                color = EInkTheme.Colors.darkGray,
                modifier = Modifier.padding(bottom = 8.dp)
            )
        }

        // View mode toggle
        // Inline legend — shows only action types present in current results
        val presentActions = remember(planResult) {
            planResult.proposals.map { it.action }.distinct()
        }
        InlineActionLegend(actions = presentActions)

        Spacer(modifier = Modifier.height(8.dp))

        ViewModeToggle(
            selectedMode = viewMode,
            onModeSelected = { viewMode = it },
            modifier = Modifier.padding(bottom = 12.dp)
        )

        // Content based on view mode
        Box(
            modifier = Modifier
                .fillMaxWidth()
                .weight(1f, fill = false)  // Oct 2026: keeps its height where it fits, shrinks so the buttons stay on a small screen
                .height(440.dp)
        ) {
            when (viewMode) {
                OptimizeViewMode.LIST -> {
                    // List view (existing implementation)
                    LazyColumn(
                        state = scrollState,
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(bottom = if (showScrollIndicator) 24.dp else 0.dp),
                        verticalArrangement = Arrangement.spacedBy(10.dp)
                    ) {
                        items(planResult.proposals) { proposal ->
                            ProposalCard(
                                proposal = proposal,
                                isActioned = handledProposalIds.contains(proposal.id),
                                onExecute = {
                                    if (!handledProposalIds.contains(proposal.id)) {
                                        onExecuteProposal(proposal)
                                    }
                                },
                                onSkip = {
                                    if (!handledProposalIds.contains(proposal.id)) {
                                        onSkipProposal(proposal)
                                    }
                                }
                            )
                        }
                    }

                    // Scroll indicator for list view
                    if (showScrollIndicator) {
                        Box(
                            modifier = Modifier
                                .align(Alignment.BottomCenter)
                                .fillMaxWidth()
                                .height(24.dp)
                                .background(EInkTheme.Colors.background)
                                .drawBehind {
                                    drawLine(
                                        color = EInkTheme.Colors.lightGray,
                                        start = Offset(0f, 0f),
                                        end = Offset(size.width, 0f),
                                        strokeWidth = 1.dp.toPx()
                                    )
                                },
                            contentAlignment = Alignment.Center
                        ) {
                            Row(
                                verticalAlignment = Alignment.CenterVertically,
                                horizontalArrangement = Arrangement.spacedBy(4.dp)
                            ) {
                                Icon(
                                    imageVector = Icons.Default.KeyboardArrowDown,
                                    contentDescription = null,
                                    tint = EInkTheme.Colors.darkGray,
                                    modifier = Modifier.size(16.dp)
                                )
                                Text(
                                    text = "more",
                                    fontSize = EInkTheme.Typography.labelSmall,
                                    color = EInkTheme.Colors.darkGray
                                )
                            }
                        }
                    }
                }

                OptimizeViewMode.TIMELINE -> {
                    TimelineView(
                        planResult = planResult,
                        actionedProposals = handledProposalIds,
                        onExecuteProposal = { proposal ->
                            if (!handledProposalIds.contains(proposal.id)) {
                                onExecuteProposal(proposal)
                            }
                        },
                        onSkipProposal = { proposal ->
                            if (!handledProposalIds.contains(proposal.id)) {
                                onSkipProposal(proposal)
                            }
                        }
                    )
                }
            }
        }

        Spacer(Modifier.height(16.dp))

        // Done button
        EinkPrimaryButton(
            text = if (remainingProposals.isEmpty()) "All Done" else "Done (${remainingProposals.size} remaining)",
            onClick = onDone,
            modifier = Modifier.fillMaxWidth()
        )
    }
}

@Composable
private fun ViewModeToggle(
    selectedMode: OptimizeViewMode,
    onModeSelected: (OptimizeViewMode) -> Unit,
    modifier: Modifier = Modifier
) {
    Row(
        modifier = modifier
            .fillMaxWidth()
            .border(0.5.dp, EInkTheme.Colors.borderStrong, RoundedCornerShape(4.dp))
            .clip(RoundedCornerShape(4.dp))
    ) {
        OptimizeViewMode.entries.forEach { mode ->
            val isSelected = selectedMode == mode
            Box(
                modifier = Modifier
                    .weight(1f)
                    .background(
                        if (isSelected) EInkTheme.Colors.darkGray
                        else EInkTheme.Colors.background
                    )
                    .noRippleClickable { onModeSelected(mode) }
                    .padding(vertical = 8.dp),
                contentAlignment = Alignment.Center
            ) {
                Text(
                    text = when (mode) {
                        OptimizeViewMode.LIST -> "List"
                        OptimizeViewMode.TIMELINE -> "Timeline"
                    },
                    fontSize = EInkTheme.Typography.labelMedium,
                    fontWeight = if (isSelected) FontWeight.Bold else FontWeight.Normal,
                    color = if (isSelected) EInkTheme.Colors.white else EInkTheme.Colors.darkGray
                )
            }
        }
    }
}

@Composable
private fun TimelineView(
    planResult: AgenticPlanResult,
    actionedProposals: Set<String>,
    onExecuteProposal: (AgenticProposal) -> Unit,
    onSkipProposal: (AgenticProposal) -> Unit
) {
    // Group proposals by suggested time (morning, afternoon, evening, anytime)
    val proposalsWithTime = planResult.proposals.filter { it.suggestedTimeBlock != null }
    val proposalsWithoutTime = planResult.proposals.filter { it.suggestedTimeBlock == null }

    // Group by time of day based on suggestedTimeBlock.startTime
    val morningProposals = proposalsWithTime.filter { proposal ->
        proposal.suggestedTimeBlock?.startTime?.let { time ->
            val hour = time.substringBefore(":").toIntOrNull() ?: 0
            hour in 5..11
        } ?: false
    }
    val afternoonProposals = proposalsWithTime.filter { proposal ->
        proposal.suggestedTimeBlock?.startTime?.let { time ->
            val hour = time.substringBefore(":").toIntOrNull() ?: 0
            hour in 12..17
        } ?: false
    }
    val eveningProposals = proposalsWithTime.filter { proposal ->
        proposal.suggestedTimeBlock?.startTime?.let { time ->
            val hour = time.substringBefore(":").toIntOrNull() ?: 0
            hour in 18..23 || hour in 0..4
        } ?: false
    }

    LazyColumn(
        modifier = Modifier.fillMaxWidth(),
        verticalArrangement = Arrangement.spacedBy(8.dp)
    ) {
        // Morning section
        if (morningProposals.isNotEmpty()) {
            item {
                TimelineSectionHeader(title = "Morning", timeRange = "6:00 - 12:00")
            }
            items(morningProposals) { proposal ->
                TimelineProposalItem(
                    proposal = proposal,
                    isActioned = actionedProposals.contains(proposal.id),
                    onExecute = { onExecuteProposal(proposal) },
                    onSkip = { onSkipProposal(proposal) }
                )
            }
        }

        // Afternoon section
        if (afternoonProposals.isNotEmpty()) {
            item {
                TimelineSectionHeader(title = "Afternoon", timeRange = "12:00 - 18:00")
            }
            items(afternoonProposals) { proposal ->
                TimelineProposalItem(
                    proposal = proposal,
                    isActioned = actionedProposals.contains(proposal.id),
                    onExecute = { onExecuteProposal(proposal) },
                    onSkip = { onSkipProposal(proposal) }
                )
            }
        }

        // Evening section
        if (eveningProposals.isNotEmpty()) {
            item {
                TimelineSectionHeader(title = "Evening", timeRange = "18:00 - 22:00")
            }
            items(eveningProposals) { proposal ->
                TimelineProposalItem(
                    proposal = proposal,
                    isActioned = actionedProposals.contains(proposal.id),
                    onExecute = { onExecuteProposal(proposal) },
                    onSkip = { onSkipProposal(proposal) }
                )
            }
        }

        // Anytime section (no specific time block)
        if (proposalsWithoutTime.isNotEmpty()) {
            item {
                TimelineSectionHeader(title = "Anytime", timeRange = "Flexible")
            }
            items(proposalsWithoutTime) { proposal ->
                TimelineProposalItem(
                    proposal = proposal,
                    isActioned = actionedProposals.contains(proposal.id),
                    onExecute = { onExecuteProposal(proposal) },
                    onSkip = { onSkipProposal(proposal) }
                )
            }
        }
    }
}

